async function _runPreview() {
    const out = document.getElementById('indPreviewResult');
    if (!out) return;
    if (!_drawerItem || _drawerItem.kind !== 'derived' || !_drawerItem.definition_id) return;
    const id = _drawerItem.definition_id;
    out.innerHTML = '<span class="spinner"></span>';
    try {
        const res = await apiPostJSON('/indicators/' + id + '/preview', {
            hospital_id: _numVal('indPrevHosp'),
            month: _val('indPrevMonth') || null,
        });
        if (!_isCurrentDrawer(id)) return;
        out.innerHTML = _previewHtml(res);
    } catch (err) {
        out.innerHTML = '<span style="color:var(--accent-red);">' + esc(_errText(err)) + '</span>';
    }
}

function _previewHtml(res) {
    const st = _STATUS[res.status] || { label: res.status, color: 'var(--text-muted)' };
    let html = _statusHtml(res.status) +
        ' <strong style="font-size:0.95rem;direction:ltr;display:inline-block;">' +
        _valueCellHtml(res.status, res.value) + '</strong>';
    if (res.numerator != null || res.denominator != null) {
        html += ' <span style="color:var(--text-muted);">(' +
            esc(_t('numerator')) + ' ' + esc(res.numerator == null ? '—' : _fmtNum(res.numerator)) +
            ' / ' + esc(_t('denominator')) + ' ' + esc(res.denominator == null ? '—' : _fmtNum(res.denominator)) + ')</span>';
    }
    if (res.message) {
        html += '<div style="color:var(--text-muted);margin-top:0.2rem;">' + esc(res.message) + '</div>';
    }
    if (res.inputs && res.inputs.length) {
        html += '<table style="width:100%;font-size:0.72rem;border-collapse:collapse;margin-top:0.35rem;">' +
            res.inputs.map(row =>
                '<tr>' +
                '<td style="padding:0.12rem 0.3rem;direction:ltr;text-align:left;"><code style="color:var(--accent-blue);">' +
                    esc(row.code) + '</code></td>' +
                '<td style="padding:0.12rem 0.3rem;color:var(--text-secondary);">' + esc(row.name || '—') + '</td>' +
                '<td style="padding:0.12rem 0.3rem;text-align:right;direction:ltr;font-weight:600;">' +
                    (row.missing
                        ? '<span style="color:var(--accent-orange);">' + esc(_t('no data')) + '</span>'
                        : esc(_fmtNum(row.value))) + '</td>' +
                '</tr>').join('') +
            '</table>';
    }
    return html;
}

