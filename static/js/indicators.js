export function openIndicatorBuilder(editId) {
    const modal = document.getElementById('indBuilderModal');
    if (!modal) return;
    const fromDrawer = _drawerItem && _drawerItem.kind === 'derived' && _drawerItem.definition_id
        ? _drawerItem.definition_id : null;
    const id = (typeof editId === 'number' && editId) ? editId : fromDrawer;
    _editingId = id || null;

    const title = document.getElementById('indBuilderTitle');
    if (title) title.textContent = _editingId ? _t('Edit indicator') : _t('New indicator');
    _clearValidation();
    _resetBuilder();
    modal.style.display = 'flex';
    _syncPermissionUI();
    if (_editingId) _fillBuilder(_editingId);
    fetchPalette();
}

export function closeIndicatorBuilder() {
    const modal = document.getElementById('indBuilderModal');
    if (modal) modal.style.display = 'none';
    _editingId = null;
}

function _resetBuilder() {
    ['indCode', 'indName', 'indGroup', 'indDesc', 'indExpr', 'indUnit',
        'indThresholdLow', 'indThresholdHigh', 'indTargetMin', 'indTargetMax'].forEach(id => {
        const el = document.getElementById(id);
        if (el) el.value = '';
    });
    const set = (id, v) => { const el = document.getElementById(id); if (el) el.value = v; };
    set('indFormulaMode', 'ratio');
    set('indResultType', 'percentage');
    set('indAggregation', 'sum');
    set('indOperator', '/');
    set('indMultiplier', '100');
    set('indDirection', 'none');
    _autoGeneratedName = '';
    _nameManuallyEdited = false;
    const code = document.getElementById('indCode');
    if (code) { code.readOnly = true; code.disabled = true; }
    const advanced = document.getElementById('indAdvancedOptions');
    if (advanced) advanced.open = false;
    _numCodes = [];
    _denCodes = [];
    _renderZones();
    _onModeChange();
    _onDirectionChange();
    _renderPreview();
}

async function _fillBuilder(id) {
    let d;
    try {
        d = await apiGet('/indicators/' + id, _FRESH);
    } catch (err) {
        _showFormError(_errText(err));
        return;
    }
    if (_editingId !== id) return; // modal was closed/reopened meanwhile
    const set = (elId, v) => { const el = document.getElementById(elId); if (el) el.value = (v == null ? '' : v); };
    set('indCode', d.code);
    set('indName', d.name);
    set('indGroup', d.group_name);
    set('indDesc', d.description);
    set('indFormulaMode', d.formula_type);
    set('indResultType', d.result_type);
    set('indUnit', d.unit);
    set('indExpr', d.expression);
    set('indAggregation', d.aggregation);
    set('indOperator', d.operator);
    set('indMultiplier', d.multiplier == null ? '' : d.multiplier);
    set('indDirection', d.direction || 'none');
    set('indThresholdLow', d.threshold_low);
    set('indThresholdHigh', d.threshold_high);
    set('indTargetMin', d.target_min);
    set('indTargetMax', d.target_max);
    _autoGeneratedName = '';
    _nameManuallyEdited = true;
    // The code is immutable (history/results keep referencing it).
    const code = document.getElementById('indCode');
    if (code) { code.readOnly = true; code.disabled = true; }
    const advanced = document.getElementById('indAdvancedOptions');
    if (advanced) {
        advanced.open = d.formula_type === 'expression' ||
            !!d.description || (d.direction && d.direction !== 'none') ||
            d.threshold_low != null || d.threshold_high != null ||
            d.target_min != null || d.target_max != null;
    }
    _numCodes = (d.numerator_codes || []).slice();
    _denCodes = (d.denominator_codes || []).slice();
    _renderZones();
    _renderPalette();
    _onModeChange();
    _onDirectionChange();
    _renderPreview();
}

// Palette of raw data elements. Rows that already carry their own formula
// are aggregates (referencing them double-counts) and code '0' is a
// form-header label — both are left out.
async function fetchPalette() {
    const box = document.getElementById('indPalette');
    if (_palette.length) { _renderPalette(); return _palette; }
    if (box) {
        box.innerHTML = '<div style="text-align:center;color:var(--text-muted);padding:1rem;">' +
            esc(_t('Loading data elements…')) + '</div>';
    }
    try {
        const rows = await apiGet('/hospitals/indicators', _FRESH);
        _palette = (Array.isArray(rows) ? rows : [])
            .filter(r => r && r.code && String(r.code) !== '0' && !r.formula)
            .map(r => ({
                code: String(r.code),
                name: r.name || String(r.code),
                group: r.group_name || '',
            }));
        _renderPalette();
        return _palette;
    } catch (err) {
        if (box) {
            box.innerHTML = '<div style="text-align:center;color:var(--accent-red);padding:1rem;">' +
                esc(_errText(err)) + '</div>';
        }
        return [];
    }
}

function _renderPalette() {
    const box = document.getElementById('indPalette');
    if (!box) return;
    const q = _val('indPaletteSearch').trim().toLowerCase();
    const list = _palette.filter(p => !q ||
        (p.code + ' ' + p.name + ' ' + p.group).toLowerCase().indexOf(q) !== -1);
    if (!list.length) {
        box.innerHTML = '<div style="text-align:center;color:var(--text-muted);padding:1rem;">' +
            esc(_t(_palette.length ? 'No data elements match the filter.' : 'No data elements available.')) +
            '</div>';
        return;
    }
    const ratioMode = _val('indFormulaMode') !== 'expression';
    box.innerHTML = list.map(p => {
        const inNum = _numCodes.indexOf(p.code) !== -1;
        const inDen = _denCodes.indexOf(p.code) !== -1;
        const tint = inNum ? 'border-color:var(--accent-green);'
            : inDen ? 'border-color:var(--accent-purple);' : '';
        return '<span class="vb-drag-chip" draggable="true" data-ind-code="' + esc(p.code) +
            '" title="' + esc(p.name) + '" style="cursor:grab;' + tint + '">' +
            '<code style="font-size:0.7rem;color:var(--accent-blue);direction:ltr;">' + esc(p.code) + '</code>' +
            '<span data-ind-add="num" style="cursor:pointer;">' + esc(p.name) + '</span>' +
            (ratioMode
                ? '<b data-ind-add="den" title="' + esc(_t('Add to the denominator')) +
                  '" style="cursor:pointer;font-size:0.68rem;color:var(--accent-purple);">＋D</b>'
                : '') +
            '</span>';
    }).join('');
}

function _onPaletteClick(e) {
    const chip = e.target.closest('[data-ind-code]');
    if (!chip) return;
    const code = chip.dataset.indCode;
    if (_val('indFormulaMode') === 'expression') {
        _insertAtCursor(code);
        return;
    }
    const add = e.target.closest('[data-ind-add]');
    _addToZone(add ? add.dataset.indAdd : 'num', code);
}

function _insertAtCursor(code) {
    const ta = document.getElementById('indExpr');
    if (!ta) return;
    const token = '{' + code + '}';
    const start = typeof ta.selectionStart === 'number' ? ta.selectionStart : ta.value.length;
    const end = typeof ta.selectionEnd === 'number' ? ta.selectionEnd : ta.value.length;
    ta.value = ta.value.slice(0, start) + token + ta.value.slice(end);
    const pos = start + token.length;
    ta.selectionStart = pos;
    ta.selectionEnd = pos;
    ta.focus();
    _syncGeneratedFields();
    _renderPreview();
}

function _addToZone(zone, code) {
    const list = zone === 'den' ? _denCodes : _numCodes;
    if (list.indexOf(code) === -1) list.push(code);
    _renderZones();
    _renderPalette();
    _syncGeneratedFields();
    _renderPreview();
}

function _removeFromZone(zone, code) {
    const list = zone === 'den' ? _denCodes : _numCodes;
    const idx = list.indexOf(code);
    if (idx !== -1) list.splice(idx, 1);
    _renderZones();
    _renderPalette();
    _syncGeneratedFields();
    _renderPreview();
}

function _renderZones() {
    const paint = (elId, codes, zone) => {
        const el = document.getElementById(elId);
        if (!el) return;
        el.innerHTML = codes.length
            ? codes.map(c =>
                '<span class="vb-drag-chip" draggable="true" data-ind-code="' + esc(c) +
                '" data-ind-zone-chip="' + zone + '">' +
                '<code style="font-size:0.72rem;color:var(--accent-blue);direction:ltr;">' + esc(c) + '</code>' +
                '<b data-ind-remove="' + zone + '" data-ind-code="' + esc(c) + '" title="' +
                esc(_t('Remove')) + '" style="cursor:pointer;color:var(--accent-red);">×</b></span>').join('')
            : '<span style="font-size:0.72rem;color:var(--text-muted);">' +
              esc(_t('Empty — pick data elements from the list below')) + '</span>';
    };
    paint('indNumZone', _numCodes, 'num');
    paint('indDenZone', _denCodes, 'den');
}

function _onZoneClick(e) {
    const rm = e.target.closest('[data-ind-remove]');
    if (!rm) return;
    _removeFromZone(rm.dataset.indRemove, rm.dataset.indCode);
}

function _onDragStart(e) {
    const chip = e.target.closest ? e.target.closest('[data-ind-code]') : null;
    if (!chip || !e.dataTransfer) return;
    const zoneEl = chip.closest('[data-ind-zone]');
    const from = chip.dataset.indZoneChip || (zoneEl ? zoneEl.dataset.indZone : 'palette');
    e.dataTransfer.setData('text/plain', JSON.stringify({ code: chip.dataset.indCode, from: from }));
}

function _onZoneDrop(e) {
    if (!e.dataTransfer) return;
    e.preventDefault();
    let payload;
    try { payload = JSON.parse(e.dataTransfer.getData('text/plain')); } catch (err) { return; }
    if (!payload || !payload.code) return;
    const zone = e.currentTarget.dataset.indZone;
    if (payload.from === 'num' || payload.from === 'den') _removeFromZone(payload.from, payload.code);
    _addToZone(zone, payload.code);
}

function _onModeChange() {
    const mode = _val('indFormulaMode');
    const ratio = document.getElementById('indRatioPanel');
    const expr = document.getElementById('indExprPanel');
    const aggregation = document.getElementById('indAggregationWrap');
    const operator = document.getElementById('indOperatorWrap');
    if (ratio) ratio.style.display = mode === 'ratio' ? '' : 'none';
    if (expr) expr.style.display = mode === 'expression' ? '' : 'none';
    if (aggregation) aggregation.style.display = mode === 'ratio' ? '' : 'none';
    if (operator) operator.style.display = mode === 'ratio' ? '' : 'none';
    _syncGeneratedFields();
    _renderPalette();
    _renderPreview();
}

function _onDirectionChange() {
    const show = _val('indDirection') === 'target_range';
    ['indTargetMinWrap', 'indTargetMaxWrap'].forEach(id => {
        const el = document.getElementById(id);
        if (el) el.style.display = show ? '' : 'none';
    });
}

// Display-only pretty print: no user formula text is ever run here.
function _renderPreview() {
    const el = document.getElementById('indFormulaPreview');
    if (!el) return;
    if (_val('indFormulaMode') === 'expression') {
        const expr = _val('indExpr').trim();
        el.textContent = expr ? '= ' + expr : '—';
        return;
    }
    if (!_numCodes.length) { el.textContent = '—'; return; }
    const agg = (_val('indAggregation') || 'sum').toUpperCase();
    const op = _val('indOperator') || '/';
    const sym = { '/': '÷', '*': '×', '+': '+', '-': '−' }[op] || op;
    const part = codes => (codes.length > 1 ? agg + '(' + codes.join(' + ') + ')' : codes[0]);
    let text = '= ' + part(_numCodes);
    if (op === '/' || _denCodes.length) {
        text += ' ' + sym + ' ' + (_denCodes.length ? part(_denCodes) : '…');
    }
    const mult = parseFloat(_val('indMultiplier'));
    if (isFinite(mult) && mult !== 1) text += ' × ' + mult;
    el.textContent = text;
}

function _collectDraft() {
    _syncGeneratedFields();
    const mode = _val('indFormulaMode');
    const draft = {
        code: _val('indCode').trim(),
        name: _val('indName').trim(),
        description: _val('indDesc').trim() || null,
        group_name: _val('indGroup').trim() || null,
        formula_type: mode || 'ratio',
        result_type: _val('indResultType') || 'percentage',
        unit: _val('indUnit').trim() || null,
        direction: _val('indDirection') || 'none',
        threshold_low: _numVal('indThresholdLow'),
        threshold_high: _numVal('indThresholdHigh'),
        target_min: _numVal('indTargetMin'),
        target_max: _numVal('indTargetMax'),
    };
    if (mode === 'expression') {
        draft.expression = _val('indExpr').trim() || null;
    } else {
        draft.numerator_codes = _numCodes.slice();
        draft.denominator_codes = _denCodes.slice();
        draft.operator = _val('indOperator') || '/';
        draft.aggregation = _val('indAggregation') || 'sum';
        // Empty multiplier is omitted: the backend default (1.0) applies
        // on create and the stored value is kept on update.
        const mult = parseFloat(_val('indMultiplier'));
        if (isFinite(mult)) draft.multiplier = mult;
    }
    return draft;
}

// PUT sends the whole draft, minus the immutable code and minus
// is_active (activation has its own /toggle endpoint).
function _updateBody(draft) {
    const body = Object.assign({}, draft);
    delete body.code;
    delete body.is_active;
    return body;
}

function _localErrors(draft) {
    const errs = [];
    if (!draft.code) errs.push(_t('Indicator ID is required'));
    else if (!/^[A-Za-z0-9._-]{1,50}$/.test(draft.code)) {
        errs.push(_t('Indicator ID must be 1-50 characters from letters, digits, ".", "_" or "-"'));
    }
    if (!draft.name) errs.push(_t('Indicator name is required'));
    return errs;
}

async function _callValidate(draft) {
    try {
        return await apiPostJSON('/indicators/validate', {
            draft: draft,
            exclude_id: _editingId || null,
        });
    } catch (err) {
        const body = _errBody(err);
        const detail = body ? body.detail : null;
        if (detail && Array.isArray(detail.errors)) {
            const res = { valid: false, errors: detail.errors, warnings: detail.warnings || [] };
            _renderValidation(res);
            return res;
        }
        _showFormError(_errText(err));
        return null;
    }
}

async function validateIndicatorDraft_impl() {
    const draft = _collectDraft();
    const local = _localErrors(draft);
    if (local.length) {
        _renderValidation({ valid: false, errors: local, warnings: [] });
        return false;
    }
    const res = await _callValidate(draft);
    if (!res) return false;
    _renderValidation(res);
    return !!res.valid;
}

async function saveIndicator_impl() {
    const saveBtn = document.getElementById('btnSaveIndicator');
    const draft = _collectDraft();
    const local = _localErrors(draft);
    if (local.length) {
        _renderValidation({ valid: false, errors: local, warnings: [] });
        return false;
    }
    if (saveBtn) saveBtn.disabled = true;
    try {
        // Contract: validate with the SERVER first — a draft the API
        // rejects is never turned into a POST/PUT.
        const res = await _callValidate(draft);
        if (!res) return false;
        _renderValidation(res);
        if (!res.valid) return false;

        let saved;
        if (_editingId) {
            saved = await apiPut('/indicators/' + _editingId, _updateBody(draft));
        } else {
            saved = await apiPostJSON('/indicators', draft);
        }
        const wasEdit = !!_editingId;
        closeIndicatorBuilder();
        toastSuccess(wasEdit ? _t('Indicator updated') : _t('Indicator created'));
        await _loadList();
        if (saved && _isCurrentDrawer(saved.id)) {
            _openDetail('derived', saved.code, saved.id);
        }
        return true;
    } catch (err) {
        const body = _errBody(err);
        const detail = body ? body.detail : null;
        if (detail && Array.isArray(detail.errors)) {
            // 422 with detail.errors — show them inside the builder.
            _renderValidation({
                valid: false,
                errors: detail.errors,
                warnings: detail.warnings || [],
            });
        } else {
            _showFormError(_errText(err));
        }
        return false;
    } finally {
        if (saveBtn) saveBtn.disabled = false;
    }
}

function _renderValidation(res) {
    const box = document.getElementById('indValidationMsgs');
    if (!box) return;
    const parts = [];
    if (res && res.valid) {
        parts.push('<div style="color:var(--accent-green);font-weight:600;">✓ ' +
            esc(_t('Valid — this draft can be saved.')) + '</div>');
        if (res.formula_display) {
            parts.push('<div style="direction:ltr;text-align:left;font-family:monospace;color:var(--text-primary);">' +
                esc(res.formula_display) + '</div>');
        }
    } else {
        parts.push('<div style="color:var(--accent-red);font-weight:600;margin-bottom:0.2rem;">' +
            esc(_t('This draft cannot be saved yet:')) + '</div>');
        parts.push('<ul style="margin:0;padding-inline-start:1.1rem;color:var(--accent-red);">' +
            ((res && res.errors) || []).map(e => '<li>' + esc(e) + '</li>').join('') + '</ul>');
    }
    const warnings = (res && res.warnings) || [];
    if (warnings.length) {
        parts.push('<div style="color:var(--accent-orange);margin-top:0.3rem;">⚠ ' +
            warnings.map(w => esc(w)).join('<br>⚠ ') + '</div>');
    }
    const refs = (res && res.refs) || [];
    if (refs.length) {
        parts.push('<div style="color:var(--text-secondary);margin-top:0.3rem;">' +
            esc(_t('References')) + ': ' +
            refs.map(r => '<code style="direction:ltr;color:' +
                (r.exists === false ? 'var(--accent-red)' : 'var(--accent-blue)') + ';">' +
                esc(r.code) + '</code>').join(' ') + '</div>');
    }
    if (res && res.preview) parts.push('<div style="margin-top:0.3rem;">' + _previewHtml(res.preview) + '</div>');
    box.innerHTML = parts.join('');
    box.style.display = 'block';
}

function _clearValidation() {
    const box = document.getElementById('indValidationMsgs');
    if (!box) return;
    box.style.display = 'none';
    box.innerHTML = '';
}

function _showFormError(msg) {
    const box = document.getElementById('indValidationMsgs');
    if (!box) { toastError(msg); return; }
    box.style.display = 'block';
    box.innerHTML = '<div style="color:var(--accent-red);font-weight:600;">' + esc(msg) + '</div>';
}

