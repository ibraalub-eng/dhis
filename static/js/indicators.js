// ── Indicators tab module ─────────────────────────────────────────────
// Management UI for app/api/indicator_definitions.py:
//   * one searchable catalog over raw data elements, existing system
//     rate definitions and managed derived indicators,
//   * the Indicator Builder (ratio zones or {code} expression) that
//     validates the draft with the SERVER before anything is saved,
//   * live preview against real data, references / stored results /
//     version history in the detail drawer,
//   * activate-deactivate and safe deletion (409 → purge confirmation).
//
// Safety rule: user formula text is NEVER executed in the browser. The
// builder only pretty-prints it into #indFormulaPreview for display —
// every parse / evaluate / preview happens server-side through
// POST /indicators/validate and POST /indicators/{id}/preview.
