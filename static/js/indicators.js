async function toggleIndicatorActive_impl() {
    const item = _drawerItem;
    if (!item || item.kind !== 'derived' || !item.definition_id) return;
    const id = item.definition_id;
    const next = item.status !== 'active';
    try {
        const res = await apiPut('/indicators/' + id + '/toggle', { is_active: next });
        item.status = (res && typeof res.is_active === 'boolean')
            ? (res.is_active ? 'active' : 'inactive')
            : (next ? 'active' : 'inactive');
        toastSuccess(next ? _t('Indicator activated') : _t('Indicator deactivated'));
        await _loadList();
        if (_isCurrentDrawer(id)) _renderDrawerActions(item);
    } catch (err) {
        toastError(_errText(err));
    }
}

async function deleteIndicator_impl() {
    const item = _drawerItem;
    if (!item || item.kind !== 'derived' || !item.definition_id) return;
    const id = item.definition_id;
    const name = item.name || item.code;
    const ok = await confirmDestructive({
        title: _t('Delete this indicator?'),
        message: _t('The definition is removed; version history is kept for the audit trail.') +
            '<br><strong>' + esc(name) + '</strong>',
        okLabel: _t('Delete'),
    });
    if (!ok) return;
    try {
        await apiDelete('/indicators/' + id);
        toastSuccess(_t('Indicator deleted') + ': ' + esc(name));
        closeIndicatorDrawer();
        await _loadList();
    } catch (err) {
        const msg = _errText(err);
        // 409 while stored results exist: offer the explicit purge path.
        if (msg.indexOf('purge') !== -1) {
            const purge = await confirmDestructive({
                title: _t('Delete the stored results too?'),
                message: esc(msg) + '<br><br>' +
                    _t('Repeat the delete with purge=true so the stored results are removed as well. Version history still survives.'),
                okLabel: _t('Delete with results'),
            });
            if (!purge) return;
            try {
                const res = await apiDelete('/indicators/' + id + '?purge=true');
                const n = (res && res.results_deleted) || 0;
                toastSuccess(_t('Indicator deleted') + ' (' + n + ' ' + _t('results purged') + ')');
                closeIndicatorDrawer();
                await _loadList();
            } catch (err2) {
                toastError(_errText(err2));
            }
            return;
        }
        toastError(msg);
    }
}

async function recomputeIndicators_impl() {
    const ok = await confirmDestructive({
        title: _t('Recompute stored results?'),
        message: _t('Every managed indicator is recalculated from raw data for the latest month; existing results for that month are replaced.'),
        okLabel: _t('Recompute'),
    });
    if (!ok) return;
    try {
        const res = await apiPostJSON('/indicators/recompute', {});
        let summary = (res && res.message) || _t('Recompute finished');
        if (res && res.counts) {
            const parts = Object.keys(res.counts)
                .filter(k => res.counts[k])
                .map(k => _t((_STATUS[k] || { label: k }).label) + ': ' + res.counts[k]);
            if (parts.length) summary += ' — ' + parts.join(', ');
        }
        toastSuccess(summary);
        if (_drawerItem && _drawerItem.kind === 'derived' && _drawerItem.definition_id) {
            const id = _drawerItem.definition_id;
            try {
                const results = await apiGet('/indicators/' + id + '/results', _FRESH);
                if (_isCurrentDrawer(id)) _renderResults((results && results.items) || []);
            } catch (e) { /* the list already refreshed */ }
        }
    } catch (err) {
        toastError(_errText(err));
    }
}

